def main():
    data = rows()
    n = len(data)
    print("articles", n)
    if n < 777:
        raise SystemExit(f"need 777+, got {n}")
    # emit a compact module that reconstructs articles from a blob
    lines = [
        '"""777+ real world-knowledge articles Cortex AGI can retrieve and train on.',
        "",
        "Facts: elements, capitals, states, planets, amino acids, SI, HTTP, languages,",
        "constellations, and STEM/CS concepts. Not slogans.",
        '"""',
        "from __future__ import annotations",
        "",
        "ROWS: list[tuple[str, tuple[str, ...], str]] = [",
    ]
    for t, tags, b in data:
        tag_s = ", ".join(repr(x) for x in tags)
        lines.append(f"    ({t!r}, ({tag_s},), {b!r}),")
    lines.append("]")
    lines.append("")
    lines.append("def world_rows() -> list[tuple[str, tuple[str, ...], str]]:")
    lines.append("    return ROWS")
    lines.append("")
    lines.append("def world_count() -> int:")
    lines.append("    return len(ROWS)")
    lines.append("")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, "bytes", OUT.stat().st_size)


